/**
 * corpus/generate.mjs — the tympan corpus: 52 documents, generated deterministically.
 *
 * Why generated, and why labelled as such: a benchmark is only honest if the
 * numbers can be reproduced. Real customer documents cannot be committed, and a
 * hand-picked set of five "representative" files is how a benchmark quietly
 * becomes marketing. So the corpus is 13 document archetypes crossed with four
 * size variants (52 sheets), each archetype carrying the thing that actually
 * breaks converters: a wide table, a hostile @media print block, a 100vh hero,
 * RTL text, CJK line breaking, a fixed header, local images, a dark theme.
 *
 * Deterministic by construction: no randomness, no dates, no network. The
 * runner records a hash over the generated bytes, so a number published in
 * docs/BENCHMARKS.md can be tied to the exact corpus that produced it.
 *
 * `tympan` never reads this file; it is benchmark furniture.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const SIZES = {
  short: 1,
  medium: 3,
  long: 8,
  extreme: 20,
};

/** Paragraph text that differs per archetype, so pages are not clones. */
const LOREM = [
  'The quick brown fox jumps over the lazy dog while the printer decides where the sheet ends.',
  'Deterministic output means the same bytes twice: identical input, identical engine, identical file.',
  'A wide table is the classic pagination failure: the row that does not fit takes the whole table with it.',
  'Print CSS injected at runtime is the reason a clean template exists at all.',
  'Whitespace is not waste, but a half-empty sheet is a page the reader pays for and does not read.',
];

const para = (seed, n = 4) => {
  const out = [];
  for (let i = 0; i < n; i++) out.push(`<p>${LOREM[(seed + i) % LOREM.length]} ${LOREM[(seed + i + 2) % LOREM.length]}</p>`);
  return out.join('\n');
};

const table = (rows, cols = 5) => {
  const head = Array.from({ length: cols }, (_, c) => `<th>Column ${c + 1}</th>`).join('');
  const body = Array.from({ length: rows }, (_, r) =>
    `<tr>${Array.from({ length: cols }, (_, c) => `<td>${r + 1}.${c + 1} value</td>`).join('')}</tr>`
  ).join('\n');
  return `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
};

/** A local image reference: the corpus ships one PNG next to the documents. */
const LOCAL_IMG = '<img src="corpus-logo.png" alt="logo" width="120" height="40">';
/** A data-URI image: always resolvable, no network, no file access. */
const INLINE_IMG =
  '<img alt="dot" width="8" height="8" src="data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==">';

const section = (id, inner, cls = 'page-section') => `<section class="${cls}" id="${id}">${inner}</section>`;

