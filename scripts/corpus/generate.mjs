const DOC = ({ title, lang, dir, css, print, body, localImg }) => `<!DOCTYPE html>
<html lang="${lang}"${dir ? ` dir="${dir}"` : ''}>
<head>
<meta charset="utf-8">
<title>${title}</title>
<style>
  html,body{margin:0;padding:0}
  main{max-width:774px;margin:0 auto;padding:8px}
  .page-section{padding:12px}
  table{border-collapse:collapse;width:100%;font-size:13px}
  th,td{border:1px solid #999;padding:4px 6px;text-align:left}
  .slide{padding:24px}
  ${css || ''}
</style>
${print ? `<style>${print}</style>` : ''}
</head>
<body>
${localImg ? `<div>${LOCAL_IMG}</div>` : ''}
<main>
${body}
</main>
</body>
</html>
`;

/**
 * The corpus, deterministically.
 * @returns {Array<{id: string, html: string, flags: string[], lang: string}>}
 */
export function buildCorpus() {
  const docs = [];
  for (const archetype of ARCHETYPES) {
    for (const [size, n] of Object.entries(SIZES)) {
      const id = `${archetype.id}-${size}`;
      docs.push({
        id,
        lang: archetype.dir === 'rtl' ? 'ar' : archetype.id === 'cjk' ? 'ja' : 'en',
        flags: archetype.flags,
        html: DOC({
          title: `${archetype.id} ${size}`,
          lang: archetype.dir === 'rtl' ? 'ar' : archetype.id === 'cjk' ? 'ja' : 'en',
          dir: archetype.dir,
          css: archetype.css,
          print: archetype.print,
          body: archetype.build(n),
          // One archetype references a local file on purpose: it is the case
          // tympan is currently worst at, and the corpus should show it.
          localImg: archetype.id === 'article',
        }),
      });
    }
  }
  return docs;
}

/** A 1×1 PNG, written beside the corpus so the file:// case is real. */
const LOGO = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAXAAAAAoCAYAAACgJ8UxAAAAAXNSR0IArs4c6QAAADZJREFUeF7t0QEBAAAAgJD+r+4ICgQoAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAQBsKdgABb6FTXwAAAABJRU5ErkJggg==',
  'base64'
);

/** SHA-256 over every document, in id order — the corpus's identity. */
export function corpusHash(docs) {
  const h = crypto.createHash('sha256');
  for (const d of [...docs].sort((a, b) => a.id.localeCompare(b.id))) {
    h.update(d.id).update('\0').update(d.html).update('\0');
  }
  return h.digest('hex').slice(0, 16);
}

/**
 * Write the corpus to a directory.
 * @param {string} dir
 * @returns {{files: string[], hash: string, count: number}}
 */
export function writeCorpus(dir) {
  const docs = buildCorpus();
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'corpus-logo.png'), LOGO);
  const files = [];
  for (const doc of docs) {
    const file = path.join(dir, `${doc.id}.html`);
    fs.writeFileSync(file, doc.html);
    files.push(file);
  }
  return { files, hash: corpusHash(docs), count: docs.length };
}

/** CLI: `node scripts/corpus/generate.mjs [dir]` — regenerates the corpus. */
if (process.argv[1] && process.argv[1].endsWith('generate.mjs')) {
  const dir = process.argv[2] || path.join(process.cwd(), 'test', 'corpus');
  const { count, hash, files } = writeCorpus(dir);
  console.log(`corpus: ${count} documents in ${dir} (hash ${hash}, ${files.length} files)`);
}
